export type Locale = "es" | "en";

const STORAGE_KEY = "audio-search-locale";

export function detectLocale(): Locale {
  const fromUrl = new URLSearchParams(window.location.search).get("lang");
  if (fromUrl === "en" || fromUrl === "es") return fromUrl;

  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === "en" || saved === "es") return saved;

  return navigator.languages.some(language => language.toLowerCase().startsWith("en")) ? "en" : "es";
}

export function persistLocale(locale: Locale): void {
  window.localStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
  window.dispatchEvent(new CustomEvent<Locale>("audio-search-locale-change", { detail: locale }));
}

